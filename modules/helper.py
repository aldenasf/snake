def validate_name(filename:str): # Verify if name is allowed to be used for a file/directory
        chars = [   
            "<",
            ">",
            ":",
            "\"",
            "/",
            "\\",
            "|",
            "?",
            "*"
        ]
        names = [
            "con", 
            "prn", 
            "aux", 
            "nul", 
            "com1", 
            "com2", 
            "com3", 
            "com4", 
            "com5", 
            "com6", 
            "com7", 
            "com8", 
            "com9", 
            "lpt1", 
            "lpt2", 
            "lpt3", 
            "lpt4", 
            "lpt5", 
            "lpt6", 
            "lpt7", 
            "lpt8", 
            "lpt9"
        ]
        if any((c in chars) for c in filename.lower()):
            return False
        if any(n in filename.lower() for n in names):
            return False
        else:
            return True
