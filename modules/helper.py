def cls(goto=None):
    os.system("cls")
    if goto and callable(goto):
        goto()
def info(message:str):
    print(terminal.info + "[i] " + message)
def error(message:str, callback):
    if not callable(callback):
        print("goto is not callable!")
    cls()
    if not message.endswith("."):
        message = message + "."
    print(terminal.error + "[!] " + message)
    callback()
